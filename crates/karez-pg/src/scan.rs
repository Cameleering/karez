//! Partitioned table scans over several connections.
//!
//! One query runs on one server backend, so one connection cannot read a large table faster than one backend
//! produces rows. [`scan_partitioned`] splits a table into disjoint ranges of heap blocks, reads each range on
//! its own connection and thread, and by default makes all of them see one snapshot of the table
//! (`pg_export_snapshot` and `SET TRANSACTION SNAPSHOT`, as `pg_dump -j` does).
//!
//! Measured effect (`docs/design/perf-program.md`): up to about 3x on a database with spare cores and a fast
//! link, about 1.2x when the link is the limit (1.9 Gbit/s). A few partitions are enough; more only add load.
//!
//! The partitions are ranges of `ctid` (a TID range scan, PostgreSQL 14 or later), so no key column is needed and
//! the planner reads each range sequentially. Only ordinary tables are supported; the order of rows is not
//! defined.

use crate::config::Config;
use crate::conn::{quote_ident, Connection};
use crate::error::{Error, Result};
use karez_chunk::Chunk;
use karez_proto_pg::Value;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Barrier;

/// What to scan and how.
#[derive(Debug, Clone)]
pub struct Scan<'a> {
    table: &'a str,
    columns: &'a [&'a str],
    partitions: usize,
    snapshot: bool,
}

/// The default number of partitions when none is set: the client's CPUs, at most 8.
pub fn default_partitions() -> usize {
    std::thread::available_parallelism()
        .map(|n| n.get())
        .unwrap_or(4)
        .clamp(1, 8)
}

impl<'a> Scan<'a> {
    /// Scan `columns` of `table`. `table` may be `name` or `schema.name`; each part is quoted, so a name that
    /// contains a dot is not supported. `columns` must not be empty.
    pub fn new(table: &'a str, columns: &'a [&'a str]) -> Self {
        Scan {
            table,
            columns,
            partitions: 0,
            snapshot: true,
        }
    }

    /// The number of connections. 0 (the default) means [`default_partitions`]. 1 reads the whole table on one
    /// connection.
    pub fn partitions(mut self, n: usize) -> Self {
        self.partitions = n;
        self
    }

    /// Read every partition from one snapshot (the default). With `false` the partitions run in separate
    /// statements and may see different states of the table if it changes while the scan runs.
    pub fn snapshot(mut self, on: bool) -> Self {
        self.snapshot = on;
        self
    }
}

/// Quote `name` or `schema.name`.
pub(crate) fn quoted_table(table: &str) -> Result<String> {
    let mut parts = Vec::new();
    for p in table.split('.') {
        parts.push(quote_ident(p)?);
    }
    if parts.len() > 2 {
        return Err(Error::Usage("table must be name or schema.name"));
    }
    Ok(parts.join("."))
}

/// The column list and the table, quoted.
fn select_prefix(scan: &Scan<'_>) -> Result<String> {
    if scan.columns.is_empty() {
        return Err(Error::Usage("a scan needs at least one column"));
    }
    let mut cols = Vec::new();
    for c in scan.columns {
        cols.push(quote_ident(c)?);
    }
    Ok(format!(
        "SELECT {} FROM {}",
        cols.join(", "),
        quoted_table(scan.table)?
    ))
}

/// Heap block range `[lo, hi)` of partition `p` of `n` over `blocks` blocks. The last partition is open-ended
/// (`hi` is `None`) so blocks added after the size was read are still covered when no snapshot is used.
pub(crate) fn block_range(blocks: i64, n: usize, p: usize) -> (i64, Option<i64>) {
    let n = n as i64;
    let p = p as i64;
    let lo = blocks * p / n;
    let hi = if p == n - 1 {
        None
    } else {
        Some(blocks * (p + 1) / n)
    };
    (lo, hi)
}

/// Snapshot identifiers are generated by the server (`00000003-0000001B-1`). `SET TRANSACTION SNAPSHOT`
/// accepts only a string constant, so the id is the one value that is put into SQL text, after this check.
pub(crate) fn valid_snapshot_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 64 && id.bytes().all(|b| b.is_ascii_hexdigit() || b == b'-')
}

fn one_i64(conn: &mut Connection, sql: &str, params: &[Value<'_>]) -> Result<i64> {
    let mut cur = conn.query(sql, params)?;
    let row = cur.next()?.ok_or(Error::Usage("expected one row"))?;
    let v = row.get::<i64>(0)?;
    cur.close()?;
    Ok(v)
}

/// Read one partition and feed its chunks to `on_chunk`.
fn run_partition<S>(
    conn: &mut Connection,
    prefix: &str,
    range: Option<(i64, Option<i64>)>,
    state: &mut S,
    on_chunk: &(dyn Fn(&mut S, &Chunk) -> Result<()> + Sync),
    abort: &AtomicBool,
) -> Result<()> {
    let (lo, hi) = match range {
        Some((lo, hi)) => (format!("({lo},0)"), hi.map(|h| format!("({h},0)"))),
        None => (String::new(), None),
    };
    let mut cur = match (range.is_some(), hi.as_deref()) {
        (false, _) => conn.query(prefix, &[])?,
        (true, None) => conn.query(
            &format!("{prefix} WHERE ctid >= $1::text::tid"),
            &[Value::Text(&lo)],
        )?,
        (true, Some(h)) => conn.query(
            &format!("{prefix} WHERE ctid >= $1::text::tid AND ctid < $2::text::tid"),
            &[Value::Text(&lo), Value::Text(h)],
        )?,
    };
    while let Some(chunk) = cur.next_chunk()? {
        if abort.load(Ordering::Relaxed) {
            break; // another partition failed; the cursor's drop drains the rest
        }
        on_chunk(state, chunk)?;
    }
    Ok(())
}

/// Scan a table on several connections at once.
///
/// For each partition `p`, `init(p)` creates its state, and `on_chunk(&mut state, &chunk)` is called on that
/// partition's thread for every chunk it reads (up to 1,024 rows or 1 MiB). Chunks of different partitions
/// arrive concurrently and in no defined order; the states come back in partition order. The first error stops
/// the other partitions and is returned.
///
/// ```ignore
/// let cols = ["id", "amount"];
/// let sums = karez_pg::scan_partitioned(
///     &cfg,
///     &karez_pg::Scan::new("public.orders", &cols).partitions(4),
///     |_| 0i64,
///     |sum, chunk| {
///         for v in chunk.column(1)?.data().chunks_exact(8) {
///             *sum += i64::from_le_bytes(v.try_into().unwrap());
///         }
///         Ok(())
///     },
/// )?;
/// let total: i64 = sums.iter().sum();
/// ```
///
/// Needs PostgreSQL 14 or later (TID range scans). A table without any heap block (empty, or not an ordinary
/// table such as a view) is read on one connection with a plain query.
pub fn scan_partitioned<S, I, F>(
    cfg: &Config,
    scan: &Scan<'_>,
    init: I,
    on_chunk: F,
) -> Result<Vec<S>>
where
    S: Send,
    I: Fn(usize) -> S + Sync,
    F: Fn(&mut S, &Chunk) -> Result<()> + Sync,
{
    let prefix = select_prefix(scan)?;
    let table_text = quoted_table(scan.table)?;
    let want = if scan.partitions == 0 {
        default_partitions()
    } else {
        scan.partitions
    };

    // The leader reads the size, exports the snapshot and scans partition 0.
    let mut leader = Connection::connect(cfg)?;
    if want > 1 {
        let ver = leader
            .server_param("server_version")
            .and_then(|v| v.split('.').next().and_then(|m| m.parse::<u32>().ok()))
            .unwrap_or(0);
        if ver < 14 {
            return Err(Error::Usage(
                "partitioned scans need PostgreSQL 14 or later (TID range scans)",
            ));
        }
    }
    let blocks = if want > 1 {
        one_i64(
            &mut leader,
            "SELECT (pg_relation_size($1::text::regclass) / current_setting('block_size')::int8)::int8",
            &[Value::Text(&table_text)],
        )?
    } else {
        0
    };
    let n = if blocks == 0 {
        1
    } else {
        want.min(blocks as usize)
    };
    let abort = AtomicBool::new(false);

    if n == 1 {
        let mut st = init(0);
        run_partition(&mut leader, &prefix, None, &mut st, &on_chunk, &abort)?;
        return Ok(vec![st]);
    }

    let mut snapshot_id: Option<String> = None;
    if scan.snapshot {
        leader.execute("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY", &[])?;
        let id = {
            let mut cur = leader.query("SELECT pg_export_snapshot()", &[])?;
            let row = cur.next()?.ok_or(Error::Usage("no snapshot returned"))?;
            let s = row.get::<&str>(0)?.to_string();
            cur.close()?;
            s
        };
        if !valid_snapshot_id(&id) {
            return Err(Error::Usage("the server returned an unusable snapshot id"));
        }
        snapshot_id = Some(id);
    }

    // Every worker must have imported the snapshot before the leader may commit, so all `n` threads meet here,
    // also after an error.
    let imported = Barrier::new(n);
    let (init, on_chunk, abort, imported, prefix, snapshot_id) =
        (&init, &on_chunk, &abort, &imported, &prefix, &snapshot_id);

    let results: Vec<Result<S>> = std::thread::scope(|sc| {
        let handles: Vec<_> = (1..n)
            .map(|p| {
                sc.spawn(move || -> Result<S> {
                    let setup = (|| -> Result<Connection> {
                        let mut c = Connection::connect(cfg)?;
                        if let Some(id) = snapshot_id {
                            c.execute("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY", &[])?;
                            c.execute(&format!("SET TRANSACTION SNAPSHOT '{id}'"), &[])?;
                        }
                        Ok(c)
                    })();
                    if setup.is_err() {
                        abort.store(true, Ordering::Relaxed);
                    }
                    imported.wait();
                    let mut c = setup?;
                    let mut st = init(p);
                    run_partition(
                        &mut c,
                        prefix,
                        Some(block_range(blocks, n, p)),
                        &mut st,
                        on_chunk,
                        abort,
                    )
                    .inspect_err(|_| abort.store(true, Ordering::Relaxed))?;
                    if snapshot_id.is_some() {
                        c.execute("COMMIT", &[])?;
                    }
                    Ok(st)
                })
            })
            .collect();
        imported.wait();
        let mut out = Vec::with_capacity(n);
        let mut st = init(0);
        let r0 = if abort.load(Ordering::Relaxed) {
            Err(Error::Usage("another partition failed to start"))
        } else {
            run_partition(
                &mut leader,
                prefix,
                Some(block_range(blocks, n, 0)),
                &mut st,
                on_chunk,
                abort,
            )
        };
        if r0.is_err() {
            abort.store(true, Ordering::Relaxed);
        }
        out.push(r0.map(|()| st));
        for h in handles {
            out.push(
                h.join()
                    .unwrap_or(Err(Error::Usage("a partition thread panicked"))),
            );
        }
        out
    });

    if snapshot_id.is_some() {
        leader.execute("COMMIT", &[])?;
    }
    // The first real error wins over the "another partition failed" echoes.
    let mut states = Vec::with_capacity(n);
    let mut real: Option<Error> = None;
    let mut echo: Option<Error> = None;
    for r in results {
        match r {
            Ok(s) => states.push(s),
            Err(e) if matches!(&e, Error::Usage(m) if m.starts_with("another partition")) => {
                echo.get_or_insert(e);
            }
            Err(e) => {
                real.get_or_insert(e);
            }
        }
    }
    match real.or(echo) {
        Some(e) => Err(e),
        None => Ok(states),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn blocks_are_covered_exactly_once() {
        for blocks in [1i64, 2, 7, 100, 1001] {
            for n in 1..=8usize {
                let mut next = 0;
                for p in 0..n {
                    let (lo, hi) = block_range(blocks, n, p);
                    assert_eq!(lo, next, "blocks {blocks} n {n} p {p}");
                    match hi {
                        Some(h) => {
                            assert!(h >= lo);
                            next = h;
                        }
                        None => {
                            assert_eq!(p, n - 1);
                            next = blocks;
                        }
                    }
                }
                assert_eq!(next, blocks);
            }
        }
    }

    #[test]
    fn snapshot_ids_are_checked() {
        assert!(valid_snapshot_id("00000003-0000001B-1"));
        assert!(valid_snapshot_id("0A-1"));
        assert!(!valid_snapshot_id(""));
        assert!(!valid_snapshot_id("00000003'; DROP TABLE x; --"));
        assert!(!valid_snapshot_id("0000 0003"));
        assert!(!valid_snapshot_id(&"A".repeat(65)));
    }

    #[test]
    fn table_names_are_quoted() {
        assert_eq!(quoted_table("orders").unwrap(), "\"orders\"");
        assert_eq!(
            quoted_table("public.orders").unwrap(),
            "\"public\".\"orders\""
        );
        assert_eq!(quoted_table("we\"ird").unwrap(), "\"we\"\"ird\"");
        assert!(quoted_table("a.b.c").is_err());
        assert!(quoted_table("").is_err());
        assert!(quoted_table("a.").is_err());
    }

    #[test]
    fn select_text_is_assembled_from_quoted_identifiers() {
        let cols = ["id", "na\"me"];
        let s = Scan::new("public.t", &cols);
        assert_eq!(
            select_prefix(&s).unwrap(),
            "SELECT \"id\", \"na\"\"me\" FROM \"public\".\"t\""
        );
        let none: [&str; 0] = [];
        assert!(select_prefix(&Scan::new("t", &none)).is_err());
    }
}
