-- A small back-office schema: customers, catalogue, orders, payments, invoices, stock, audit.
SET ROLE karez_scram;

CREATE SEQUENCE order_no_seq START 100000;

CREATE TABLE customers (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          text        NOT NULL UNIQUE,
    name           text        NOT NULL,
    phone          text,                      -- NULL for a third of the rows
    notes          text,                      -- NULL for most rows
    legacy_code    text,                      -- always NULL
    created_at     timestamptz NOT NULL DEFAULT now(),
    is_active      boolean     NOT NULL DEFAULT true,
    loyalty_points int         NOT NULL DEFAULT 0 CHECK (loyalty_points >= 0),
    status         varchar(16) NOT NULL DEFAULT 'new'
                   CHECK (status IN ('new','active','vip','closed'))
);

CREATE TABLE addresses (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint   NOT NULL REFERENCES customers(id),
    line1       text     NOT NULL,
    line2       text,
    city        text     NOT NULL,
    postal_code text     NOT NULL,
    country     char(2)  NOT NULL,
    is_default  boolean  NOT NULL DEFAULT false
);

CREATE TABLE categories (
    id        int PRIMARY KEY,
    name      text NOT NULL UNIQUE,
    parent_id int REFERENCES categories(id)
);

CREATE TABLE products (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             text   NOT NULL UNIQUE,
    name            text   NOT NULL,
    description     text,
    category_id     int    NOT NULL REFERENCES categories(id),
    price_cents     bigint NOT NULL CHECK (price_cents >= 0),
    weight_kg       float4,
    rating          float8,
    created_at      timestamptz NOT NULL DEFAULT now(),
    discontinued_on date
);

CREATE TABLE inventory (
    product_id bigint PRIMARY KEY REFERENCES products(id),
    on_hand    int NOT NULL CHECK (on_hand >= 0),
    reserved   int NOT NULL DEFAULT 0 CHECK (reserved >= 0)
);

CREATE TABLE orders (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no        text   NOT NULL UNIQUE DEFAULT ('ORD-' || nextval('order_no_seq')),
    customer_id     bigint NOT NULL REFERENCES customers(id),
    ship_address_id bigint NOT NULL REFERENCES addresses(id),
    placed_at       timestamptz NOT NULL DEFAULT now(),
    status          text   NOT NULL DEFAULT 'placed'
                    CHECK (status IN ('placed','paid','shipped','cancelled')),
    total_cents     bigint NOT NULL DEFAULT 0 CHECK (total_cents >= 0),
    note            text
);

CREATE TABLE order_items (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         bigint NOT NULL REFERENCES orders(id),
    line_no          int2   NOT NULL,
    product_id       bigint NOT NULL REFERENCES products(id),
    qty              int2   NOT NULL CHECK (qty > 0),
    unit_price_cents bigint NOT NULL CHECK (unit_price_cents >= 0),
    discount_pct     float4,
    UNIQUE (order_id, line_no)
);

CREATE TABLE payments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint NOT NULL REFERENCES orders(id),
    amount_cents bigint NOT NULL CHECK (amount_cents >= 0),
    method       text   NOT NULL CHECK (method IN ('card','transfer','cash')),
    paid_at      timestamptz NOT NULL,
    reference    uuid   NOT NULL UNIQUE
);

CREATE TABLE refunds (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id   bigint NOT NULL REFERENCES payments(id),
    amount_cents bigint NOT NULL CHECK (amount_cents > 0),
    reason       text,
    refunded_at  timestamptz NOT NULL
);

CREATE TABLE invoices (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id  bigint NOT NULL UNIQUE REFERENCES orders(id),
    issued_on date   NOT NULL,
    due_on    date   NOT NULL,
    pdf       bytea,
    CHECK (due_on >= issued_on)
);

CREATE TABLE inventory_movements (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products(id),
    delta      int    NOT NULL,
    reason     text   NOT NULL,
    moved_at   timestamptz NOT NULL DEFAULT now(),
    order_id   bigint REFERENCES orders(id)
);

CREATE TABLE audit_log (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at      timestamptz NOT NULL DEFAULT now(),
    actor   text   NOT NULL,
    action  text   NOT NULL,
    details text
);

CREATE INDEX orders_customer_idx      ON orders(customer_id);
CREATE INDEX order_items_order_idx    ON order_items(order_id);
CREATE INDEX order_items_product_idx  ON order_items(product_id);
CREATE INDEX payments_order_idx       ON payments(order_id);
CREATE INDEX movements_product_idx    ON inventory_movements(product_id);
CREATE INDEX audit_at_idx             ON audit_log(at);

CREATE VIEW v_order_summary AS
SELECT o.id AS order_id, o.order_no, c.id AS customer_id, c.name AS customer_name,
       o.status, o.placed_at, count(oi.id) AS item_count,
       sum(oi.qty * oi.unit_price_cents)::int8 AS items_cents, o.total_cents
  FROM orders o
  JOIN customers c ON c.id = o.customer_id
  LEFT JOIN order_items oi ON oi.order_id = o.id
 GROUP BY o.id, c.id;

RESET ROLE;
